# operators in python 
a = 100
b = 10
c = True
d = False
print(a-b)# output -> 90
print(a+b)# output -> 110
print(a/b)# output -> 10.0 (/) gives an float value
print(a*b)# output -> 1000
print(a//b)# output -> 10 (//) gives an int value
print(a%b)# output -> 0
print(c or d)# output -> true
print(c and d)# output -> false
print(not c)# output -> false
print(not d)# output -> true
